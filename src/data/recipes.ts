export const recipeBySlug = new Map(recipes.map((r) => [r.slug, r]))

export function getRecipe(slug: string): Recipe | undefined {
  return recipeBySlug.get(slug)
}

/** Cuisines that actually appear on the shelf, with counts, for the sidebar. */
export function cuisineCounts() {
  const counts = new Map<Cuisine, number>()
  for (const r of recipes) counts.set(r.cuisine, (counts.get(r.cuisine) ?? 0) + 1)
  return [...counts.entries()].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))
}

export function timeOfDayCounts() {
  const counts = new Map<TimeOfDay, number>()
  for (const r of recipes)
    for (const t of r.timeOfDay) counts.set(t, (counts.get(t) ?? 0) + 1)
  return TIMES_OF_DAY.filter((t) => counts.has(t)).map(
    (t) => [t, counts.get(t)!] as const,
  )
}

export function tagCounts() {
  const counts = new Map<string, number>()
  for (const r of recipes)
    for (const tag of r.tags) counts.set(tag, (counts.get(tag) ?? 0) + 1)
  return [...counts.entries()]
    .filter(([, n]) => n > 1)
    .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))
}
